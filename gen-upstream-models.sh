#!/usr/bin/env bash
# Regenerate model entries in config.yaml from model-alias-map.json.
#
#   model-alias-map.json : local model_name -> upstream router model id   (hand-maintained)
#   model-base-map.json  : upstream model id -> LiteLLM price-map key      (model_info.base_model)
#
# Local names (e.g. claude_sonnet_5_5) are stable and are what clients and virtual keys use.
# When upstream renames a model, change ONLY the right-hand side in model-alias-map.json
# (and the key in model-base-map.json), rerun this script, recreate the container.
#
# Fails (config.yaml unchanged) if any mapped upstream id is missing from upstream /v1/models,
# so a rename can never silently drop a model.
#
# LEGACY_UPSTREAM=1 also emits the old "upstream/<id>" names (transition only).
#
# Reads UPSTREAM_LITELLM_API_BASE / UPSTREAM_LITELLM_API_KEY from the environment or .env.
# Usage: ./gen-upstream-models.sh && docker compose up -d --force-recreate litellm
set -euo pipefail
cd "$(dirname "$0")"

[ -f .env ] && { set -a; . ./.env; set +a; }
: "${UPSTREAM_LITELLM_API_BASE:?set UPSTREAM_LITELLM_API_BASE}"
: "${UPSTREAM_LITELLM_API_KEY:?set UPSTREAM_LITELLM_API_KEY}"

ALIAS_FILE=model-alias-map.json
BASEMAP_FILE=model-base-map.json
[ -f "$ALIAS_FILE" ] || { echo "ERROR: $ALIAS_FILE missing" >&2; exit 1; }
[ -f "$BASEMAP_FILE" ] || echo '{}' > "$BASEMAP_FILE"

AUTH_HEADER="Authorization: Bearer ${UPSTREAM_LITELLM_API_KEY}"
UPSTREAM_IDS=$(curl -fsS -m 30 "${UPSTREAM_LITELLM_API_BASE%/}/v1/models" -H "$AUTH_HEADER" | jq -c '[.data[].id]')
[ "$UPSTREAM_IDS" != "[]" ] || { echo "ERROR: upstream returned no models; config.yaml unchanged" >&2; exit 1; }

UPSTREAM_IDS="$UPSTREAM_IDS" LEGACY_UPSTREAM="${LEGACY_UPSTREAM:-0}" python3 -I - <<'PY'
import json, os, re, sys
alias = {k: v for k, v in json.load(open("model-alias-map.json")).items() if not k.startswith("_")}
base = json.load(open("model-base-map.json"))
up = set(json.loads(os.environ["UPSTREAM_IDS"]))
legacy = os.environ.get("LEGACY_UPSTREAM") == "1"

missing = {loc: uid for loc, uid in alias.items() if uid not in up}
if missing:
    print("ERROR: upstream no longer serves these mapped models (config.yaml unchanged):", file=sys.stderr)
    for loc, uid in missing.items():
        stem = "-".join(uid.split("-")[:2])
        cands = sorted(i for i in up if i.startswith(stem))[:10]
        print(f"  {loc} -> {uid}   candidates: {cands}", file=sys.stderr)
    print("Fix model-alias-map.json (right-hand side) and model-base-map.json, then rerun.", file=sys.stderr)
    sys.exit(1)
bad = [k for k in alias if not re.fullmatch(r"[a-z0-9_]+", k)]
if bad:
    sys.exit(f"ERROR: local names must be [a-z0-9_]: {bad}")
vals = list(alias.values())
dups = {v for v in vals if vals.count(v) > 1}
if dups:
    sys.exit(f"ERROR: upstream id mapped twice: {dups}")

def entry(name, uid):
    s = (f"  - model_name: {name}\n    litellm_params:\n      model: litellm_proxy/{uid}\n"
         f"      api_base: os.environ/UPSTREAM_LITELLM_API_BASE\n      api_key: os.environ/UPSTREAM_LITELLM_API_KEY\n")
    if uid in base:
        s += f"    model_info:\n      base_model: {base[uid]}\n"
    else:
        print(f"WARN: no base_model for {uid} in model-base-map.json -> spend will be $0", file=sys.stderr)
    return s

block = "".join(entry(loc, uid) for loc, uid in sorted(alias.items()))
if legacy:
    block += "  # legacy upstream/<id> names (transition; regenerate without LEGACY_UPSTREAM=1 to drop)\n"
    block += "".join(entry(f"upstream/{uid}", uid) for uid in sorted(alias.values()))

p = "config.yaml"
s = open(p).read()
pat = re.compile(r"  # BEGIN upstream-models.*?# END upstream-models", re.S)
if not pat.search(s):
    sys.exit("markers not found in config.yaml")
new = "  # BEGIN upstream-models (generated by gen-upstream-models.sh - do not edit)\n" + block + "  # END upstream-models"
open(p, "w").write(pat.sub(lambda m: new, s))
print(f"Updated config.yaml: {len(alias)} models" + (f" + {len(alias)} legacy upstream/* names" if legacy else ""))
PY
